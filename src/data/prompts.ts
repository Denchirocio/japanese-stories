export interface VocabWord {
  word: string
  furigana?: string
  romaji: string
  translation: string
}

export interface RequiredVerb {
  word: string
  furigana: string
  translation: string
  form: string
}

export interface RequiredAdjective {
  word: string
  furigana?: string
  romaji: string
  translation: string
  type: 'い' | 'な'
}

export interface DailyPrompt {
  level: 'N5' | 'N4'
  grammar: string
  // Punto gramatical opcional (N5 o N4 como mucho): no es obligatorio usarlo,
  // pero si se usa bien suma puntos extra en la corrección.
  bonusGrammar: string
  themeTitle: string
  themeFurigana: string
  themeTranslation: string
  topic: string
  vocab: VocabWord[]
  verbs: RequiredVerb[]
  adjectives: RequiredAdjective[]
  places: VocabWord[]
}

